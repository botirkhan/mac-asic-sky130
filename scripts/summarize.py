#!/usr/bin/env python3
"""Collect LibreLane metrics from every run into one markdown table.

usage: summarize.py <artifact_root> <out.md>

<artifact_root> holds runs/<tag>/final/metrics.json from each flow job and
gl/<tag>.md from each gate-level simulation. The Artix-7 column comes from the
pipelined-mac-accelerator repo (Vivado 2026.1, out of context).
"""
import json
import re
import sys
from pathlib import Path

root, out = Path(sys.argv[1]), Path(sys.argv[2])

TT = "nom_tt_025C_1v80"
SS = "max_ss_100C_1v60"


def num(m, key):
    v = m.get(key)
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


def ws_corner(m, corner):
    return num(m, f"timing__setup__ws__corner:{corner}")


def fmt(v, spec="{:.3f}", none="n/a"):
    return none if v is None else spec.format(v)


runs = []
for mf in sorted(root.glob("runs/*/final/metrics.json")):
    tag = mf.parent.parent.name
    m = json.loads(mf.read_text())
    period = float(re.sub(r"[^0-9.]", "", tag) or "nan")
    gl = root / "gl" / f"{tag}.md"
    gl_line = "not run"
    if gl.exists():
        g = re.search(r"\*\*gl: (.*?)\*\*", gl.read_text())
        gl_line = g.group(1) if g else "see log"
    runs.append((period, tag, m, gl_line))
runs.sort(key=lambda r: -r[0])

lines = [
    "# SKY130 implementation results",
    "",
    "Generated by CI (`.github/workflows/asic.yml`) from LibreLane `final/metrics.json`.",
    "Library: `sky130_fd_sc_hd`. Fmax estimates use 1 / (period − setup WNS) at that corner.",
    "",
    "| Clock target | Setup WNS (ss, 100 °C, 1.60 V) | Setup WNS (tt, 25 °C, 1.80 V) | Fmax est. ss / tt | Hold WNS | Setup / hold violations | Std-cell area | Cells | Die area | Utilization | Power | DRC (Magic / KLayout) | LVS errors | Antenna nets | Gate-level sim |",
    "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
]
for period, tag, m, gl_line in runs:
    ss, tt = ws_corner(m, SS), ws_corner(m, TT)
    if ss is None:
        ss = num(m, "timing__setup__ws")
    f_ss = 1000.0 / (period - ss) if ss is not None and period - ss > 0 else None
    f_tt = 1000.0 / (period - tt) if tt is not None and period - tt > 0 else None
    power = num(m, "power__total")
    die = num(m, "design__die__area")
    util = num(m, "design__instance__utilization")
    lines.append(
        "| {p:g} ns ({mhz:.0f} MHz) | {ss} ns | {tt} ns | {fss} / {ftt} MHz | {hold} ns | {sv} / {hv} | {area} µm² | {cells} | {die} µm² | {util} | {pw} | {md} / {kd} | {lvs} | {ant} | {gl} |".format(
            p=period, mhz=1000.0 / period,
            ss=fmt(ss), tt=fmt(tt),
            fss=fmt(f_ss, "{:.0f}"), ftt=fmt(f_tt, "{:.0f}"),
            hold=fmt(num(m, "timing__hold__ws")),
            sv=fmt(num(m, "timing__setup_vio__count"), "{:.0f}"),
            hv=fmt(num(m, "timing__hold_vio__count"), "{:.0f}"),
            area=fmt(num(m, "design__instance__area"), "{:,.0f}"),
            cells=fmt(num(m, "design__instance__count"), "{:,.0f}"),
            die=fmt(die, "{:,.0f}"),
            util=fmt(util * 100 if util is not None else None, "{:.1f}%"),
            pw=fmt(power * 1000 if power is not None else None, "{:.2f} mW"),
            md=fmt(num(m, "magic__drc_error__count"), "{:.0f}"),
            kd=fmt(num(m, "klayout__drc_error__count"), "{:.0f}"),
            lvs=fmt(num(m, "design__lvs_error__count"), "{:.0f}"),
            ant=fmt(num(m, "antenna__violating__nets"), "{:.0f}"),
            gl=gl_line,
        )
    )

if not runs:
    lines.append("| (no completed runs) |" + " |" * 14)

lines += [
    "",
    "## Same RTL on the Artix-7 FPGA (for comparison)",
    "",
    "From [pipelined-mac-accelerator](https://github.com/botirkhan/pipelined-mac-accelerator) "
    "(xc7a100tcsg324-1, Vivado 2026.1, out of context): timing met at 250 MHz with WNS +0.874 ns "
    "(about 320 MHz), and the whole datapath packs into **1 DSP48E1** plus 8 flip-flops. "
    "On SKY130 there is no hard DSP block, so the 16×16 multiplier and 40-bit adder are built "
    "from standard cells, which is where the area above goes.",
    "",
]
out.write_text("\n".join(lines))
print("\n".join(lines))
